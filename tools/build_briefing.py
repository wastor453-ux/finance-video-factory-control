#!/usr/bin/env python3
"""Build BRIEFING.md: one file with everything a Claude needs, so a chat-only Claude (no clone, no folder access)
can get the full state from ONE raw link. The driver runs this before every commit; check_repo.py fails if it is stale.
Usage: python3 tools/build_briefing.py [repo_root]"""
import os, re, sys

PARTS = ["START_HERE.md", "PROJECT_BIBLE.md", "STATUS.md", "DECISIONS.md", "PATCHES.md", "MUSE_PLAYBOOK.md"]


def rd(p):
    with open(p, encoding="utf8") as f:
        return f.read()


def build(root):
    j = lambda *a: os.path.join(root, *a)
    out = ["# BRIEFING (generated by tools/build_briefing.py; do not edit by hand)\n",
           "Everything a Claude needs, in one file. Source of truth is the repo files named in each section. "
           "Files in your own chat uploads (old zips, `transcript-fix.zip`, `finance-video-factory-control-starter.zip`, old PDFs) are NOT the source of truth; if they disagree with this briefing, this briefing wins.\n"]
    for n in PARTS:
        if os.path.exists(j(n)):
            out.append(f"\n\n---\n# [{n}]\n\n{rd(j(n)).strip()}\n")
    hd = j("HANDOFFS")
    if os.path.exists(j("HANDOFFS", "LATEST.md")):
        out.append(f"\n\n---\n# [HANDOFFS/LATEST.md]\n\n{rd(j('HANDOFFS', 'LATEST.md')).strip()}\n")
    if os.path.exists(j("LOG.md")):
        txt = rd(j("LOG.md"))
        entries = re.split(r"(?m)^(?=## \d{4}-\d{2}-\d{2}(?:-\d+)? \|)", txt)[1:]
        out.append("\n\n---\n# [LOG.md] last 10 entries\n\n" + "\n".join(e.strip() + "\n" for e in entries[-10:]))
    for d in ("doing", "todo"):
        dd = j("JOBS", d)
        for n in sorted(os.listdir(dd)) if os.path.isdir(dd) else []:
            if n.endswith(".md"):
                out.append(f"\n\n---\n# [JOBS/{d}/{n}]\n\n{rd(os.path.join(dd, n)).strip()}\n")
    return "".join(out).rstrip() + "\n"


if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    with open(os.path.join(root, "BRIEFING.md"), "w", encoding="utf8") as f:
        f.write(build(root))
    print("BRIEFING.md written")
